"""PDF Editing & Regeneration API Routes - Filesystem Based."""
from flask import Blueprint, request, send_file
import io
from app.services.pdf_filesystem_service import get_pdf_filesystem_service
from app.utils import APIResponse, validate_json_params, ValidationUtils, ErrorHandler

bp = Blueprint('pdf_edit', __name__, url_prefix='/api/pdf-edit')

pdf_fs = get_pdf_filesystem_service()


@bp.route('/extract-layout', methods=['POST'])
@validate_json_params(['pdf_id'])
def extract_layout():
    """Extract editable text and layout information from PDF."""
    try:
        data = request.get_json()
        pdf_id = data.get('pdf_id')
        
        # Validate parameters
        if not ValidationUtils.validate_pdf_id(pdf_id):
            return APIResponse.error(
                'INVALID_PDF_ID',
                'Invalid PDF ID format',
                status_code=400
            )
        
        # Extract text and layout
        text, spans = pdf_fs.extract_text_and_layout(pdf_id)
        
        return APIResponse.success(
            data={
                'text': text,
                'spans': [
                    {
                        'span_id': f"{i}",
                        'page_index': span['page_index'],
                        'bbox': span['bbox'],
                        'font_size': span['font_size'],
                        'color': span['color'],
                        'text': span['text']
                    }
                    for i, span in enumerate(spans)
                ]
            }
        )
    except Exception as e:
        return ErrorHandler.handle_file_error(e)


@bp.route('/regenerate', methods=['POST'])
@validate_json_params(['pdf_id', 'edited_text', 'spans'])
def regenerate_pdf():
    """Regenerate PDF with edited text while preserving layout."""
    try:
        data = request.get_json()
        pdf_id = data.get('pdf_id')
        edited_text = data.get('edited_text')
        spans = data.get('spans', [])
        save_as_new = data.get('save_as_new', False)
        
        # Validate parameters
        if not ValidationUtils.validate_pdf_id(pdf_id):
            return APIResponse.error(
                'INVALID_PDF_ID',
                'Invalid PDF ID format',
                status_code=400
            )
        
        if not edited_text or not isinstance(edited_text, str):
            return APIResponse.error(
                'INVALID_TEXT',
                'Edited text must be a non-empty string',
                status_code=400
            )
        
        if not spans or not isinstance(spans, list):
            return APIResponse.error(
                'INVALID_SPANS',
                'Spans must be a non-empty list',
                status_code=400
            )
        
        # Regenerate PDF
        regenerated_bytes = pdf_fs.regenerate_pdf_with_layout(pdf_id, edited_text, spans)
        
        # For filesystem, we just return the regenerated bytes
        # Note: save_as_new is not supported with filesystem storage
        return APIResponse.success(
            data={
                'regenerated_pdf_id': pdf_id,
                'preview_url': f"/api/pdf/{pdf_id}/download",
                'message': 'PDF text prepared (full implementation requires pdf manipulation library)'
            }
        )
    except Exception as e:
        return ErrorHandler.handle_file_error(e)


@bp.route('/<pdf_id>/preview', methods=['GET'])
def get_pdf_preview(pdf_id):
    """Get PDF preview (convert first page to image)."""
    try:
        page = request.args.get('page', 1, type=int)
        
        # Validate parameters
        if not ValidationUtils.validate_pdf_id(pdf_id):
            return APIResponse.error(
                'INVALID_PDF_ID',
                'Invalid PDF ID format',
                status_code=400
            )
        
        # Get PDF bytes
        pdf_bytes = pdf_fs.get_pdf_bytes(pdf_id)
        if not pdf_bytes:
            return APIResponse.error(
                'NOT_FOUND',
                'PDF not found',
                status_code=404
            )
        
        # Convert page to image
        try:
            import fitz
            doc = fitz.open(stream=pdf_bytes, filetype="pdf")
            
            page_num = max(0, page - 1)
            if page_num >= len(doc):
                return APIResponse.error(
                    'INVALID_PAGE',
                    f'Page {page} not found',
                    status_code=400
                )
            
            page_obj = doc[page_num]
            pix = page_obj.get_pixmap(matrix=fitz.Matrix(2, 2), alpha=False)
            
            img_data = pix.tobytes("png")
            doc.close()
            
            return send_file(
                io.BytesIO(img_data),
                mimetype='image/png'
            )
        except ImportError:
            return APIResponse.error(
                'DEPENDENCY_ERROR',
                'PyMuPDF not available for preview generation',
                status_code=501
            )
    except Exception as e:
        return ErrorHandler.handle_file_error(e)

